import type { Block, Inline } from './body';

/**
 * The kinds of question HANDOFF §6.5 asks the site to carry an explicit
 * answer for. One article each, and no two articles share one.
 */
export type QuestionKind =
  /** ما هو ربائد؟ */
  | 'definition'
  /** ربائد مقابل واتساب والبريد والإكسل — «الفئة الأضعف حالياً وهي الأكثر طلباً في محركات التوليد». */
  | 'comparison'
  /** كيف تمر المعاملة من الطلب إلى الاعتماد؟ */
  | 'how'
  /** مكتب هندسي يدير عدة مشاريع. */
  | 'useCase'
  /** ماذا لو رفض المقاول استخدامه؟ ماذا عن بياناتنا؟ */
  | 'objection'
  /** من يقف خلف ربائد؟ أين مقرّها؟ */
  | 'entity';

export type LaunchArticle = {
  /** The page's heading, and the first half of its tab. */
  readonly title: string;
  readonly slug: string;
  /** Shown under the title on the blog index, and as the page's search description. */
  readonly summary: string;
  /** The answer-first opening paragraph: 30 to 60 words, refused outside that. */
  readonly answer: string;
  readonly body: readonly Block[];
};

